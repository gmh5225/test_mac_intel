static void field_diff(const char *name, const void *a, const void *b, size_t n)
{
	const unsigned char *x = a, *y = b;
	for (size_t i = 0; i < n; ++i)
		if (x[i] != y[i])
			printf(" %s+%zu=%02x/%02x", name, i, x[i], y[i]);
}

